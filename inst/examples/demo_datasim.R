# ── ANALYTICS PIPELINE RESULTS ------------------------------------------------
# study$analytics is a named list (one entry per snapshot).
# Each snapshot slot contains the raw gsm.core output:
#   $results   — named list of metric results (Analysis_kri0001, …)
#   $mapped    — mapped data frames (Mapped_SUBJ, Mapped_AE, Mapped_COUNTRY, …)
#   $lWorkflow — the workflow list used (useful for passing to reporting)
#   $summary   — lightweight metadata for the snapshot

snap_analytics <- study$analytics[["2012-01-31"]]  # adjust date to match your run
names(snap_analytics)

# All metric names computed for this snapshot
metric_names <- names(snap_analytics$results)
cat("Metrics computed:", paste(metric_names, collapse = ", "), "\n")

# Each metric result contains multiple data frames — no more by_site / by_country split
kri <- snap_analytics$results[[metric_names[1]]]
names(kri)  # e.g. Analysis_Summary, Analysis_Flagged, Analysis_Analyzed

kri$Analysis_Summary   # one row per site/country, with Score and Flag columns
kri$Analysis_Flagged   # subset of flagged entities
kri$Analysis_Analyzed  # full analyzed data before scoring

# Tally metrics across all snapshots
total <- sum(sapply(study$analytics, function(s) length(s$results)))
cat("Total metric results across all snapshots:", total, "\n")


