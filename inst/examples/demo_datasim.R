# ── DATA GENERATION ONLY ------------------------------------------------
# If you only need simulated raw data — no analytics, no reporting — use
# `create_longitudinal_study()` with both pipelines disabled.
# This is the fastest way to get Raw_* data frames across multiple snapshots.

data_only <- create_longitudinal_study(
  study_id         = "DATA-001",
  participants     = 200,
  sites            = 15,
  snapshots        = 6,
  interval         = "1 month",
  domains          = c("AE", "LB", "VISIT", "QUERY", "SUBJ"),
  run_analytics    = FALSE,  # skip analytics
  run_reporting    = FALSE,  # skip reporting
  verbose          = TRUE
)

# The study object has raw data but no analytics or reporting slots
names(data_only)          # $study_id, $config, $raw_data
names(data_only$raw_data) # one entry per snapshot date

# Peek at snapshots 1 and 4
snap <- data_only$raw_data[[1]]
snap4 <- data_only$raw_data[[4]]
names(snap)              # Raw_SUBJ, Raw_AE, Raw_LB, …
nrow(snap$Raw_SUBJ)      # participant count in first snap
nrow(snap4$Raw_SUBJ)     # participant count in 4th snap
nrow(snap$Raw_AE)        # AE records in first snapshot
nrow(snap4$Raw_AE)       # AE records in 4th snapshot


