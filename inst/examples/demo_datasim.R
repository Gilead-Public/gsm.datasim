# ── 8. LOW-LEVEL CONFIG API ------------------------------------------------
# For full control over dataset counts, temporal settings, and which
# analytics / reporting packages / workflows to run, use the config API.
# All functions return a modified config so they compose with pipes.

custom_study <- create_study_config(
  study_id            = "CUSTOM-001",
  participant_count   = 300,
  site_count          = 20,
  analytics_package   = "gsm.kri",
  analytics_workflows = c("kri0001", "kri0002", "kri0003"),  # only these KRIs
  reporting_package   = "gsm.reporting"                       # default but explicit
) |>
  set_temporal_config(
    start_date     = "2023-06-01",
    snapshot_count = 12,
    snapshot_width = "months"
  ) |>
  add_dataset_config("Raw_AE",    enabled = TRUE) |>
  add_dataset_config("Raw_LB",    enabled = TRUE) |>
  add_dataset_config("Raw_VISIT", enabled = TRUE) |>
  add_dataset_config("Raw_QUERY", enabled = TRUE) |>
  add_dataset_config("Raw_DATACHG", enabled = TRUE,
    count_formula = function(config, snapshot_idx = 1) {
      round(config$study_params$participant_count * 0.4 * snapshot_idx /
              config$temporal_config$snapshot_count)
    }
  )

# Inspect before generating
str(custom_study$study_params)
str(custom_study$temporal_config)
names(custom_study$dataset_configs)

# Generate raw data from config
raw_data <- generate_raw_data_from_config(custom_study, verbose = TRUE)

# Run analytics
analytics <- generate_analytics_layers(raw_data, custom_study, verbose = TRUE)

# Run reporting
reporting <- generate_reporting_layers(analytics, custom_study, verbose = TRUE)

# Wrap into a study object if you want the helper functions
study_obj <- create_longitudinal_study_data(
  study_id = custom_study$study_params$study_id,
  raw_data = raw_data,
  config   = list(
    participants = custom_study$study_params$participant_count,
    sites        = custom_study$study_params$site_count,
    snapshots    = custom_study$temporal_config$snapshot_count,
    interval     = paste(1, custom_study$temporal_config$snapshot_width),
    domains      = gsub("^Raw_", "", names(custom_study$dataset_configs))
  )
)
study_obj$analytics  <- analytics
study_obj$reporting  <- reporting

summarize_longitudinal_study(study_obj)


# ── EXPORTING STUDY DATA ------------------------------------------------
# `export_study_data()` writes a completed study to a structured folder
# hierarchy on disk.  Every snapshot date becomes a subdirectory with up to
# four sub-folders:
#
#   <output_dir>/<study_id>/
#     <snapshot_date>/
#       raw/          ← Raw_*.csv
#       mapped/       ← Mapped_*.csv     (when analytics ran)
#       analytics/    ← <metric>_<table>.csv  (when analytics ran)
#       reporting/    ← Reporting_*.csv  (when reporting ran)
#
# Folders are only created when the data actually exists.

# Export the study created above to a temporary directory.
# Returns the path to the study root folder invisibly.
study_path <- export_study_data(
  study      = study,        # longitudinal_study object from quick_longitudinal_study()
  output_dir = tempdir(),    # top-level root (default: getwd())
  verbose    = TRUE          # print per-snapshot progress
)

# ── Export options ------------------------------------------------

# Specify a different root folder and/or override the study folder name
export_study_data(
  study        = study,
  output_dir   = ".",
  format = "parquet",
  study_folder = "DEMO-001-export",  # instead of deriving from study_id
  overwrite    = TRUE                # allow re-running without error
)

# save_rds = TRUE writes analytics_full.rds per snapshot alongside the CSVs,
# preserving workflow lists, summaries, and other non-data-frame objects.
rds_path <- export_study_data(
  study      = study,
  output_dir = tempdir(),
  overwrite  = TRUE,
  save_rds   = TRUE
)

# Reload the full analytics object from the first snapshot
analytics_snap <- readRDS(file.path(rds_path, snap_date, "analytics_full.rds"))
